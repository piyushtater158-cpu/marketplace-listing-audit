def _seed(name: str) -> tuple[list[str], list[dict]]:
    with open(SEED_DIR / f"{name}.csv", encoding="utf-8") as f:
        reader = csv.DictReader(io.StringIO("".join(l for l in f if not l.lstrip().startswith("#"))))
        return reader.fieldnames, list(reader)


def _typed(field: str, value: str):
    if field in DATES:
        return date.fromisoformat(value)
    if field in NUMERIC:
        return float(value)
    return value


def _xlsx(name: str, title_row: bool = True, pretty_headers: bool = True, data_sheet_index: int = 0) -> bytes:
    """Seed file as an Excel workbook shaped like a marketplace export: typed cells, a
    report title above the header and 'Snapshot Date'-style headers."""
    fields, rows = _seed(name)
    wb = openpyxl.Workbook()
    sheets = [wb.active] + [wb.create_sheet(f"Sheet{i + 2}") for i in range(data_sheet_index)]
    if data_sheet_index:
        sheets[0].title = "Read me"
        sheets[0].append(["This export was generated by Seller Hub"])
    ws = sheets[data_sheet_index]
    if title_row:
        ws.append([f"{name.title()} report, generated 19 Oct 2026"])
    ws.append([f.replace("_", " ").title() if pretty_headers else f for f in fields])
    for r in rows:
        ws.append([_typed(f, r[f]) for f in fields])
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def _ods(name: str) -> bytes:
    fields, rows = _seed(name)

    def cell(field, value):
        if field in DATES:
            return f'<table:table-cell office:value-type="date" office:date-value="{value}"><text:p>{value}</text:p></table:table-cell>'
        if field in NUMERIC:
            return f'<table:table-cell office:value-type="float" office:value="{value}"><text:p>{value}</text:p></table:table-cell>'
        return f'<table:table-cell office:value-type="string"><text:p>{escape(value)}</text:p></table:table-cell>'

    header = "".join(cell("", f) for f in fields)
    body = "".join("<table:table-row>" + "".join(cell(f, r[f]) for f in fields) + "</table:table-row>" for r in rows)
    content = (
        '<?xml version="1.0" encoding="UTF-8"?><office:document-content '
        'xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" '
        'xmlns:table="urn:oasis:names:tc:opendocument:xmlns:table:1.0" '
        'xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0" office:version="1.2">'
        f'<office:body><office:spreadsheet><table:table table:name="{name}">'
        f"<table:table-row>{header}</table:table-row>{body}"
        "</table:table></office:spreadsheet></office:body></office:document-content>"
    )
    manifest = (
        '<?xml version="1.0" encoding="UTF-8"?><manifest:manifest '
        'xmlns:manifest="urn:oasis:names:tc:opendocument:xmlns:manifest:1.0" manifest:version="1.2">'
        f'<manifest:file-entry manifest:full-path="/" manifest:media-type="{ODS}"/>'
        '<manifest:file-entry manifest:full-path="content.xml" manifest:media-type="text/xml"/>'
        "</manifest:manifest>"
    )
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(zipfile.ZipInfo("mimetype"), ODS, compress_type=zipfile.ZIP_STORED)
        z.writestr("META-INF/manifest.xml", manifest)
        z.writestr("content.xml", content)
    return buf.getvalue()


def _csv(name: str, mutate=None, delimiter=",", encoding="utf-8") -> bytes:
    fields, rows = _seed(name)
    if mutate:
        for r in rows:
            mutate(r)
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=fields, delimiter=delimiter)
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue().encode(encoding, errors="replace")


def _upload(client, **files):
    """files: slot -> (filename, bytes)."""
    return client.post("/api/upload", files={k: (fn, data, "application/octet-stream") for k, (fn, data) in files.items()})


def _audit_signature(client):
    client.post("/api/audit/run")
    issues = client.get("/api/issues", params={"status": "all"}).json()
    return sorted((i["sku"], i["platform"], i["issue_code"], i["impact_inr"]) for i in issues)


@pytest.fixture()
def csv_signature(client):
    resp = _upload(client, listings=("listings.csv", _csv("listings")), ads=("ads.csv", _csv("ads")),
                   reviews=("reviews.csv", _csv("reviews")))
    assert resp.status_code == 200
    return _audit_signature(client)


def test_excel_upload_audits_exactly_like_the_csv(client, csv_signature):
    resp = _upload(client, listings=("Flipkart Listings.xlsx", _xlsx("listings")), ads=("ads.xlsx", _xlsx("ads")),
                   reviews=("reviews.xlsx", _xlsx("reviews")))
    assert resp.status_code == 200, resp.text
    assert resp.json()["listings"] == 480 and resp.json()["ads"] == 3360 and resp.json()["reviews"] == 265
    assert _audit_signature(client) == csv_signature


