def test_day_first_dates_semicolons_and_windows_encoding(client, csv_signature):
    def day_first(r):
        y, m, d = r["review_date"].split("-")
        r["review_date"] = f"{d}/{m}/{y}"

    first_review = _seed("reviews")[1][0]

    def day_first_with_dash(r):
        day_first(r)
        if r["text"] == first_review["text"] and r["sku"] == first_review["sku"]:
            r["text"] = "Delivery was quick – works as expected"

    resp = _upload(client, listings=("listings.csv", _csv("listings", delimiter=";")), ads=("ads.csv", _csv("ads")),
                   reviews=("reviews.csv", _csv("reviews", mutate=day_first_with_dash, encoding="cp1252")))
    assert resp.status_code == 200, resp.text
    assert _audit_signature(client) == csv_signature
    texts = {r["text"] for r in client.get(f"/api/sku/{first_review['sku']}").json()["reviews"]}
    assert "Delivery was quick – works as expected" in texts


def test_unreadable_date_is_rejected_at_upload_with_its_row(client):
    def bad(r):
        if r["sku"] == _seed("listings")[1][0]["sku"]:
            r["snapshot_date"] = "next tuesday"

    resp = _upload(client, listings=("listings.csv", _csv("listings", mutate=bad)), ads=("ads.csv", _csv("ads")),
                   reviews=("reviews.csv", _csv("reviews")))
    assert resp.status_code == 400
    assert "listings.csv: row 2" in resp.json()["detail"] and "next tuesday" in resp.json()["detail"]


def test_unsupported_and_corrupt_files_get_clear_errors(client):
    before = client.get("/api/portfolio").json()
    pdf = _upload(client, listings=("report.pdf", b"%PDF-1.7"), ads=("ads.csv", _csv("ads")),
                  reviews=("reviews.csv", _csv("reviews")))
    assert pdf.status_code == 400 and "unsupported file type '.pdf'" in pdf.json()["detail"]

    corrupt = _upload(client, listings=("listings.xlsx", b"PK\x03\x04 not really a workbook"),
                      ads=("ads.csv", _csv("ads")), reviews=("reviews.csv", _csv("reviews")))
    assert corrupt.status_code == 400 and "could not read the spreadsheet" in corrupt.json()["detail"]

    wrong = io.BytesIO()
    wb = openpyxl.Workbook()
    wb.active.append(["sku", "platform", "price"])
    wb.create_sheet("Notes").append(["nothing here"])
    wb.save(wrong)
    missing = _upload(client, listings=("Seller Hub export.xlsx", wrong.getvalue()), ads=("ads.csv", _csv("ads")),
                      reviews=("reviews.csv", _csv("reviews")))
    detail = missing.json()["detail"]
    assert missing.status_code == 400
    assert detail.startswith("Listings file 'Seller Hub export.xlsx': missing column(s) snapshot_date")
    assert "checked sheets: Sheet, Notes" in detail
    assert client.get("/api/portfolio").json() == before
