"""Builds web/app/globals.css from the Claude Design handoff's globals.css.

The handoff's PAGE sections reuse class names with different rules per route (.main,
.cell, .count, .sec-head ...), so each PAGE section is scoped under a page class that the
route puts on its root <div class="app ...">. SHARED rules pass through unchanged.
Font family literals are swapped for the CSS variables next/font defines.

Usage: npm run gen:css   (from web/)
"""

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent.parent / "design" / "listing-audit-handoff" / "globals.css"
TARGET = HERE.parent / "app" / "globals.css"
EXTRA = HERE / "extra.css"

PAGE_CLASSES = {
    "Main": "pg-overview",
    "OverviewFresh": "pg-fresh",
    "Queue": "pg-queue",
    "QueueEmpty": "pg-queue-empty",
    "Sku": "pg-sku",
    "SkuSingle": "pg-sku-single",
    "Brand": "pg-brand",
}

FONTS = {
    "'Instrument Sans'": "var(--font-instrument)",
    "'IBM Plex Mono'": "var(--font-plex-mono)",
    "'Newsreader'": "var(--font-newsreader)",
}


def split_selectors(selector: str) -> list[str]:
    parts, depth, cur = [], 0, ""
    for ch in selector:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    parts.append(cur.strip())
    return [p for p in parts if p]


def scope_rule(line: str, page_class: str) -> str:
    brace = line.index("{")
    selectors = split_selectors(line[:brace])
    scoped = ",".join(f".{page_class} {s}" for s in selectors)
    return scoped + line[brace:]


def main() -> None:
    out = [
        "/* GENERATED by web/scripts/scope_css.py from design/listing-audit-handoff/globals.css.",
        "   Edit the handoff file or scripts/extra.css, then run `npm run gen:css`. */",
        "",
    ]
    page_class = None
    in_comment = False
    for raw in SOURCE.read_text(encoding="utf-8").splitlines():
        line = raw
        for literal, var in FONTS.items():
            line = line.replace(literal, var)

        stripped = line.strip()
        if in_comment or stripped.startswith("/*"):
            match = re.search(r"PAGE:\s*(\w+)", stripped)
            if match:
                page_class = PAGE_CLASSES[match.group(1)]
                line = f"{line}  /* scoped under .{page_class} */"
            elif "SHARED" in stripped:
                page_class = None
            in_comment = not stripped.endswith("*/")
            out.append(line)
            continue

        if page_class and "{" in stripped and not stripped.startswith(":root"):
            out.append(scope_rule(stripped, page_class))
        else:
            out.append(line)

    out += ["", EXTRA.read_text(encoding="utf-8").rstrip(), ""]
    TARGET.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
